package com.tigshop.service.product;

import com.tigshop.bean.model.product.ProductGallery;
import com.tigshop.service.common.BaseService;

import java.util.List;

/**
 * 商品相册服务
 *
 * @author Tigshop团队
 * @create 2024年11月27日 15:29
 */
public interface ProductGalleryService extends BaseService<ProductGallery> {
    /**
     * 根据商品ID查询商品相册列表
     *
     * @param productId 商品ID
     * @return List
     */
    List<ProductGallery> getProductGalleryList(Integer productId);

    /**
     * 根据商品ID和门店ID查询商品相册列表，门店无独立相册时回退平台相册
     *
     * @param productId 商品ID
     * @param shopId 门店ID，0=平台
     * @return List
     */
    List<ProductGallery> getProductGalleryList(Integer productId, Long shopId);
}
