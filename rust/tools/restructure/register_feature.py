#!/usr/bin/env python3
"""Register a newly implemented feature into the v2 module tree.

Given a feature whose four-layer files already exist on disk, wire it into:
  - services/<ctx>/mod.rs     (module + `Services` field)
  - core/src/models/<ctx>/mod.rs          (if models layer)
  - infrastructure/.../repo/<ctx>/mod.rs  (if repo layer: module + field + ctor)
  - bin/src/main.rs           (service construction + ctx bundle field)
  - api route aggregators     (regenerated by tools/restructure/sync_routes.py)

Examples
--------
    # service + admin anonymous route + public anonymous route, no repo/models
    python tools/restructure/register_feature.py --ctx system --feature csrf \
        --service-type CsrfService --layers service,admin_public,public_anonymous \
        --ctor-args "cache.clone()"

    # full stack feature
    python tools/restructure/register_feature.py --ctx catalog --feature comment \
        --service-type CommentService \
        --layers models,repo,service,admin_route,public_route
"""
from __future__ import annotations

import argparse
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CR = os.path.join(ROOT, "crates")


def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read()


def write(p, t):
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(t)


def add_mod(text, feature):
    """Insert `pub mod <feature>;` in sorted position among mod decls."""
    line = "pub mod %s;" % feature
    if line in text:
        return text, False
    lines = text.splitlines()
    idx = None
    for i, ln in enumerate(lines):
        m = re.match(r"pub mod (\w+);", ln)
        if m and m.group(1) > feature:
            idx = i
            break
    if idx is None:
        last = None
        for i, ln in enumerate(lines):
            if re.match(r"pub mod (\w+);", ln):
                last = i
        idx = (last + 1) if last is not None else len(lines)
    lines.insert(idx, line)
    return "\n".join(lines) + "\n", True


def add_struct_field(text, anchor, line, before="\n}"):
    """Insert `line` inside the struct whose declaration contains `anchor`."""
    i = text.find(anchor)
    if i < 0:
        raise SystemExit("anchor not found: %s" % anchor)
    brace = text.index("{", i)
    end = text.index(before, brace)
    if line.strip() in text[brace:end]:
        return text, False
    return text[:end] + "\n" + line + text[end:], True


def add_bundle_field(text, ctx, feature):
    anchor = "let %s = Arc::new(tigshop_services::%s::Services {" % (ctx, ctx)
    i = text.find(anchor)
    if i < 0:
        raise SystemExit("ctx bundle not found: %s" % ctx)
    end = text.index("});", i)
    line = '        %s: %s.clone(),' % (feature, feature)
    if line.strip() in text[i:end]:
        return text, False
    return text[:end] + line + "\n" + text[end:], True


def add_ctor(text, ctx, feature, service_type, ctor_args):
    if re.search(r"\blet\s+%s\s*=" % re.escape(feature), text):
        return text, False
    line = "    let %s = Arc::new(%s::new(%s));" % (feature, service_type, ctor_args)
    marker = "    // ---- %s 域 ----" % ctx
    i = text.find(marker)
    if i >= 0:
        return text[:i] + line + "\n" + text[i:], True
    # fallback: before the first bundle
    m = re.search(r"\n    let \w+ = Arc::new\(tigshop_services::\w+::Services \{", text)
    if not m:
        raise SystemExit("no bundle marker in main.rs")
    return text[:m.start()] + "\n" + line + text[m.start():], True


def ensure_import(text, ctx):
    path = "use tigshop_services::%s::%s::%s;" % (ctx, "", "")
    return text


def add_use_line(text, want, prefix):
    """Insert `want` sorted among lines starting with `prefix`."""
    if want in text:
        return text, False
    lines = text.splitlines()
    candidates = [(i, ln) for i, ln in enumerate(lines) if ln.startswith(prefix)]
    if not candidates:
        # append after the last top-level `use` line
        last = max((i for i, ln in enumerate(lines) if ln.startswith("use ")), default=0)
        lines.insert(last + 1, want)
        return "\n".join(lines) + "\n", True
    for i, ln in candidates:
        if ln > want:
            lines.insert(i, want)
            return "\n".join(lines) + "\n", True
    i = candidates[-1][0]
    lines.insert(i + 1, want)
    return "\n".join(lines) + "\n", True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ctx", required=True)
    ap.add_argument("--feature", required=True)
    ap.add_argument("--service-type", required=True)
    ap.add_argument("--layers", default="service",
                    help="models,repo,service,admin_route,admin_public,public_route,"
                         "public_anonymous,public_authorized,admin_root,public_root")
    ap.add_argument("--ctor-args", default="repos.clone()")
    ap.add_argument("--repo-type", default=None,
                    help="rs 类型名，默认 <Feature>Repository")
    args = ap.parse_args()
    layers = [x.strip() for x in args.layers.split(",") if x.strip()]
    ctx, feature = args.ctx, args.feature
    pascal = "".join(p.capitalize() for p in feature.split("_")) if False else None

    changed = []

    # 1) services/<ctx>/mod.rs
    if "service" in layers:
        p = os.path.join(CR, "services/src", ctx, "mod.rs")
        t = read(p)
        t, ch = add_mod(t, feature)
        field = "    pub %s: Arc<%s::%s>," % (feature, feature, args.service_type)
        t, ch2 = add_struct_field(t, "pub struct Services {", field)
        write(p, t)
        if ch or ch2:
            changed.append(p)

    # 2) models/<ctx>/mod.rs
    if "models" in layers:
        p = os.path.join(CR, "core/src/models", ctx, "mod.rs")
        t = read(p)
        t, ch = add_mod(t, feature)
        write(p, t)
        if ch:
            changed.append(p)

    # 3) repo/<ctx>/mod.rs
    if "repo" in layers:
        p = os.path.join(CR, "infrastructure/src/db/repo", ctx, "mod.rs")
        t = read(p)
        t, ch = add_mod(t, feature)
        repo_type = args.repo_type
        if not repo_type:
            src = read(os.path.join(CR, "infrastructure/src/db/repo", ctx, feature + ".rs"))
            m = re.search(r"pub struct (\w+Repository)", src)
            if not m:
                raise SystemExit("cannot detect Repository type in %s" % feature)
            repo_type = m.group(1)
        field = "    pub %s: %s::%s," % (feature, feature, repo_type)
        t, ch2 = add_struct_field(t, "pub struct Repositories {", field)
        anchor = "impl Repositories {"
        i = t.find(anchor)
        if i < 0:
            raise SystemExit("repo impl not found")
        # insert ctor before closing `}` of `pub fn new`
        j = t.index("Self {", i)
        k = t.index("\n        }", j)
        ctor = '            %s: %s::%s::new(pool.clone()),' % (feature, feature, repo_type)
        if ctor.strip() not in t[j:k]:
            t = t[:k] + "\n" + ctor + t[k:]
            ch2 = True
        write(p, t)
        if ch or ch2:
            changed.append(p)

    # 4) bin/src/main.rs
    if "service" in layers:
        p = os.path.join(CR, "bin/src/main.rs")
        t = read(p)
        # import for the service type, grouped with other tigshop_services imports
        use_line = "use tigshop_services::%s::%s::%s;" % (
            ctx, feature, args.service_type)
        t, ch0 = add_use_line(t, use_line, "use tigshop_services::")
        t, ch = add_ctor(t, ctx, feature, args.service_type, args.ctor_args)
        t, ch2 = add_bundle_field(t, ctx, feature)
        write(p, t)
        if ch or ch2 or ch0:
            changed.append(p)

    # 5) route aggregators are derived from disk
    import sync_routes
    sync_routes.run()

    print("registered %s::%s (layers=%s)" % (ctx, feature, ",".join(layers)))
    for c in changed:
        print("  wired:", os.path.relpath(c, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
