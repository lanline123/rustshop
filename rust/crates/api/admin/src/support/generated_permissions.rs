/// 按方法 + 实际请求路径查所需权限（无条目 → None，表示不校验）。
#[must_use]
pub fn required(method: &str, path: &str) -> Option<&'static [&'static str]> {
    PERMISSIONS
        .iter()
        .find(|(m, p, _)| *m == method && path_matches(p, path))
        .map(|(_, _, perms)| *perms)
}

/// `{param}` 单段通配匹配。
#[must_use]
pub fn path_matches(pattern: &str, path: &str) -> bool {
    if !pattern.contains('{') {
        return pattern == path;
    }
    let p: Vec<&str> = pattern.trim_matches('/').split('/').collect();
    let a: Vec<&str> = path.trim_matches('/').split('/').collect();
    if p.len() != a.len() {
        return false;
    }
    p.iter().zip(a.iter()).all(|(pat, seg)| {
        (pat.starts_with('{') && pat.ends_with('}')) || pat == seg
    })
}

